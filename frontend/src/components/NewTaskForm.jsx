import { useState } from "react";
import { generateAiDescription } from "../api/taskApi.js";

export default function NewTaskForm({ onCreate, submitting }) {
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [expanded, setExpanded] = useState(false);
  const [error, setError] = useState("");
  const [generating, setGenerating] = useState(false);
  const [aiMessage, setAiMessage] = useState("");
  const [aiIsFallback, setAiIsFallback] = useState(false);
  const [showDisclaimer, setShowDisclaimer] = useState(false);

  const handleAiGenerate = async (simulateFailure = false) => {
    if (!title.trim()) {
      setError("Please enter a task title first so the AI knows what to generate.");
      return;
    }

    setError("");
    setGenerating(true);
    setExpanded(true);
    setAiMessage("");

    try {
      const res = await generateAiDescription(title.trim(), {
        simulateFailure,
        useFallback: true
      });
      const data = res.data;

      if (data.fallback && (!data.description || simulateFailure)) {
        // Step 6: Failure path demonstration - graceful fallback
        setAiIsFallback(true);
        setAiMessage(
          data.error || "⚠️ AI service unavailable. Please enter a manual description."
        );
        setShowDisclaimer(false);
      } else {
        // Step 5: Successful AI generation - editable suggestion
        setDescription(data.description || "");
        setAiIsFallback(Boolean(data.fallback));
        setAiMessage(
          data.fallback
            ? "ℹ️ Generated using local heuristic fallback. You can review and edit it below."
            : "✨ AI description generated! You can review or edit it before saving."
        );
        setShowDisclaimer(true);
      }
    } catch (err) {
      setAiIsFallback(true);
      setAiMessage("⚠️ Network error contacting AI service. Please enter a manual description.");
      setShowDisclaimer(false);
    } finally {
      setGenerating(false);
    }
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!title.trim()) {
      setError("Title can't be empty");
      return;
    }
    setError("");
    await onCreate({ title: title.trim(), description: description.trim() });
    setTitle("");
    setDescription("");
    setExpanded(false);
    setAiMessage("");
    setShowDisclaimer(false);
  };

  return (
    <form className="new-task" onSubmit={handleSubmit}>
      <div className="new-task__row">
        <span className="new-task__prompt">＋</span>
        <input
          className="new-task__input"
          placeholder="Add a task and press enter…"
          value={title}
          onChange={(e) => setTitle(e.target.value)}
          onFocus={() => setExpanded(true)}
        />
        <button
          type="button"
          className="new-task__ai-btn"
          onClick={() => handleAiGenerate(false)}
          disabled={generating || !title.trim()}
          title="Auto-generate a description using AI"
        >
          {generating ? "✨ Generating…" : "✨ AI Generate"}
        </button>
        <button className="new-task__submit" type="submit" disabled={submitting}>
          {submitting ? "Adding…" : "Add task"}
        </button>
      </div>

      {expanded && (
        <div className="new-task__expanded">
          <input
            className="new-task__description"
            placeholder="Optional description (or click ✨ AI Generate)…"
            value={description}
            onChange={(e) => setDescription(e.target.value)}
          />

          <div className="new-task__ai-toolbar">
            <span className="new-task__ai-hint">
              💡 Tip: Click <strong>✨ AI Generate</strong> to draft a description from your title.
            </span>
            <button
              type="button"
              className="new-task__ai-test-fail-btn"
              onClick={() => handleAiGenerate(true)}
              disabled={generating || !title.trim()}
              title="Test the failure path with invalid API key / error simulation"
            >
              🧪 Test Failure Path
            </button>
          </div>

          {aiMessage && (
            <div
              className={`new-task__ai-feedback ${
                aiIsFallback
                  ? "new-task__ai-feedback--fallback"
                  : "new-task__ai-feedback--success"
              }`}
            >
              {aiMessage}
            </div>
          )}

          {showDisclaimer && (
            <div className="new-task__ai-disclaimer">
              <span className="new-task__ai-disclaimer-icon">⚠️</span>
              <span>
                <strong>Responsible AI Disclaimer:</strong> This description was generated by an AI model. Please review, edit, and ensure accuracy before saving.
              </span>
            </div>
          )}
        </div>
      )}

      {error && <div className="new-task__error">{error}</div>}
    </form>
  );
}
